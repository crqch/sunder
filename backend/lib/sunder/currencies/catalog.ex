  @doc """
  Returns the full built-in ISO 4217 currency catalog entries.
  """
  def all, do: @currencies

  @doc """
  Idempotently inserts all catalog currencies into the `currencies` table.
  Existing rows (including admin overrides such as `is_active: false`) are preserved.
  """
  def sync_catalog!(repo \\ Repo) do
    now = NaiveDateTime.truncate(NaiveDateTime.utc_now(), :second)

    rows =
      Enum.map(@currencies, fn entry ->
        Map.merge(entry, %{
          is_active: true,
          inserted_at: now,
          updated_at: now
        })
      end)

    repo.insert_all(Currency, rows, on_conflict: :nothing, conflict_target: [:code])
  end
